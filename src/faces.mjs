export function drawFace(context,form,palette,x,y,scale,colors) {
  const draw=faces[form]?.[palette]??expansionFaces[palette];
  if(!draw) return;
  const color={...colors,edge:'#100f1b',void:'#090813',white:'#fff5dc',ivory:'#d6c4a8',
    fire:'#ffc271',mint:'#8be6e0',rust:'#af654e'};
  const p=(tone,points)=>{
    context.fillStyle=color[tone];
    context.beginPath();
    context.moveTo(x+points[0]*scale,y+points[1]*scale);
    for(let i=2;i<points.length;i+=2) {
      context.lineTo(x+points[i]*scale,y+points[i+1]*scale);
    }
    context.closePath();
    context.fill();
  };
  const b=(tone,dx,dy,w,h)=>{
    context.fillStyle=color[tone];
    context.fillRect(x+dx*scale,y+dy*scale,w*scale,h*scale);
  };
  const d=(tone,dx,dy,r)=>p(tone,[dx,dy-r,dx+r,dy,dx,dy+r,dx-r,dy]);
  draw({p,b,d});
}
